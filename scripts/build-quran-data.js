#!/usr/bin/env node
// One-time build script: turns two open-data npm packages into the compact
// static JSON this app ships under src/data/quran/. Re-run this after
// `npm install --no-save @sahabaplus/mushaf-engine quran-json` if the data
// ever needs regenerating (e.g. to pick up a source update).
//
// Sources:
//  - @sahabaplus/mushaf-engine (MIT) -- data/king_fahad_mushaf.json:
//    the King Fahd Complex Madani Mushaf's page-to-ayah layout (604 pages),
//    i.e. exactly which ayahs printed Mushafs place on each page.
//  - quran-json (CC-BY-4.0, by Risan Bagja Pradana) -- dist/chapters/*.json:
//    the Arabic Uthmani-style verse text and surah metadata. Only the
//    Arabic text and surah names are kept; translations/transliteration
//    are dropped (this app displays Arabic only).
//
// Output (all under src/data/quran/):
//  - pages.js   : PAGES[i] (i = page-1) = [[sura, ayah], ...] for that page
//  - text.js    : TEXT[sura-1] = [ayahText, ...] (0-indexed by ayah-1)
//  - surahs.js  : SURAHS[i] = { id, name, transliteration, type, totalVerses, startPage }

const fs = require("fs");
const path = require("path");

const MUSHAF_ENGINE = require.resolve("@sahabaplus/mushaf-engine/data/king_fahad_mushaf.json");
const QURAN_JSON_CHAPTERS = path.dirname(require.resolve("quran-json/dist/chapters/1.json"));

const OUT_DIR = path.join(__dirname, "..", "src", "data", "quran");

function license(sourceLine) {
  return (
    "// AUTO-GENERATED by scripts/build-quran-data.js -- do not hand-edit.\n" +
    "// Source: " +
    sourceLine +
    "\n"
  );
}

function main() {
  const mushafPages = JSON.parse(fs.readFileSync(MUSHAF_ENGINE, "utf8"));
  if (mushafPages.length !== 604) {
    throw new Error("expected 604 Mushaf pages, got " + mushafPages.length);
  }

  const surahs = [];
  const text = [];
  for (let id = 1; id <= 114; id++) {
    const chapter = JSON.parse(fs.readFileSync(path.join(QURAN_JSON_CHAPTERS, id + ".json"), "utf8"));
    if (chapter.verses.length !== chapter.total_verses) {
      throw new Error("surah " + id + ": verse count mismatch");
    }
    text.push(chapter.verses.map((v) => v.text));
    surahs.push({
      id: chapter.id,
      name: chapter.name,
      transliteration: chapter.transliteration,
      type: chapter.type,
      totalVerses: chapter.total_verses,
      startPage: null, // filled in below
    });
  }

  const totalAyahs = text.reduce((sum, s) => sum + s.length, 0);
  if (totalAyahs !== 6236) {
    throw new Error("expected 6236 total ayahs, got " + totalAyahs);
  }

  // Compact page structure: array of [sura, ayah] tuples per page.
  const pages = mushafPages.map((page) => page.map((e) => [e.sura, e.ayah]));

  let totalPageEntries = 0;
  pages.forEach((p) => (totalPageEntries += p.length));
  if (totalPageEntries !== 6236) {
    throw new Error("expected 6236 (sura,ayah) entries across pages, got " + totalPageEntries);
  }

  // Derive each surah's starting page number (1-indexed) from the page map.
  pages.forEach((page, pageIdx) => {
    page.forEach(([sura, ayah]) => {
      if (ayah === 1 && surahs[sura - 1].startPage === null) {
        surahs[sura - 1].startPage = pageIdx + 1;
      }
    });
  });
  surahs.forEach((s) => {
    if (s.startPage === null) throw new Error("surah " + s.id + " has no start page");
  });

  fs.mkdirSync(OUT_DIR, { recursive: true });

  fs.writeFileSync(
    path.join(OUT_DIR, "pages.js"),
    license("@sahabaplus/mushaf-engine (MIT) -- King Fahd Complex Mushaf page layout") +
      "// PAGES[i] = the [sura, ayah] pairs printed on Mushaf page i+1.\n" +
      "export var PAGES = " +
      JSON.stringify(pages) +
      ";\n"
  );

  fs.writeFileSync(
    path.join(OUT_DIR, "text.js"),
    license("quran-json (CC-BY-4.0, Risan Bagja Pradana) -- Arabic text only, adapted") +
      "// TEXT[sura-1][ayah-1] = the Arabic text of that ayah.\n" +
      "export var TEXT = " +
      JSON.stringify(text) +
      ";\n"
  );

  fs.writeFileSync(
    path.join(OUT_DIR, "surahs.js"),
    license("quran-json (CC-BY-4.0, Risan Bagja Pradana) -- surah metadata, adapted") +
      "export var SURAHS = " +
      JSON.stringify(surahs, null, 0) +
      ";\n"
  );

  console.log("Wrote", pages.length, "pages,", totalAyahs, "ayahs,", surahs.length, "surahs to", OUT_DIR);
}

main();
